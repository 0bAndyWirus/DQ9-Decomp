void UiCanvas::clear(UiColor color) {
    set_color(renderer_, color);
    SDL_RenderClear(renderer_);
}
void UiCanvas::fill(UiRect rect, UiColor color) {
    if (!renderer_ || rect.w <= 0 || rect.h <= 0) return;
    SDL_Rect r{rect.x, rect.y, rect.w, rect.h};
    set_color(renderer_, color);
    SDL_RenderFillRect(renderer_, &r);
}
void UiCanvas::outline(UiRect rect, UiColor color) {
    if (!renderer_ || rect.w <= 0 || rect.h <= 0) return;
    SDL_Rect r{rect.x, rect.y, rect.w, rect.h};
    set_color(renderer_, color);
    SDL_RenderDrawRect(renderer_, &r);
}
void UiCanvas::text(int x, int y, std::string_view value, UiColor color, int scale) {
    if (!renderer_ || scale < 1) return;
    set_color(renderer_, color);
    const int origin_x = x;
    std::array<SDL_Rect, 256> pixels;
    std::size_t count = 0;
    const auto flush = [&] {
        if (count) SDL_RenderFillRects(renderer_, pixels.data(), static_cast<int>(count));
        count = 0;
    };
    for (unsigned char raw : value) {
        if (raw == '\n') { x = origin_x; y += kLineHeight * scale; continue; }
        if (raw == '\r') continue;
        const unsigned char ch = raw >= 32 && raw <= 126 ? raw : static_cast<unsigned char>('?');
        const Glyph& g = kFont[ch - 32];
        for (int row=0; row<kGlyphHeight; ++row) {
            for (int col=0; col<kGlyphWidth; ++col) {
                if ((g[static_cast<std::size_t>(row)] & (0x80u >> col)) == 0) continue;
                pixels[count++] = SDL_Rect{x + (col + 1) * scale, y + row * scale, scale, scale};
                if (count == pixels.size()) flush();
            }
        }
        x += kCellWidth * scale;
    }
    flush();
}
int UiCanvas::text_width(std::string_view value, int scale) const {
    const int cell = kCellWidth * std::max(1, scale);
    int width = 0, current = 0;
    for (char c : value) {
        if (c == '\n') { width = std::max(width, current); current = 0; }
        else if (c != '\r') current += cell;
    }
    return std::max(width, current);
}
void UiCanvas::button(UiRect rect, std::string_view label, bool focused, bool enabled) {
    const UiColor bg = !enabled ? UiColor{35, 42, 53, 255} : focused ? UiColor{47, 104, 157, 255} : UiColor{35, 48, 68, 255};
    fill(rect, bg);
    outline(rect, focused ? UiColor{133, 211, 255, 255} : kBorder);
    text(rect.x + 12, rect.y + (rect.h - kGlyphHeight * 2) / 2, label, enabled ? kText : kMuted, 2);
}
void UiCanvas::panel(UiRect rect) {
    fill(rect, kPanel);
    outline(rect, kBorder);
}

bool save_renderer_png(SDL_Renderer* renderer, const std::filesystem::path& path, int width, int height) {
    if (!renderer || width <= 0 || height <= 0) return false;
    const std::size_t row_bytes = static_cast<std::size_t>(width) * 3;
    if (row_bytes > static_cast<std::size_t>(INT_MAX) ||
        static_cast<std::size_t>(height) > SIZE_MAX / (row_bytes + 1)) return false;
    std::vector<std::uint8_t> rgb(row_bytes * static_cast<std::size_t>(height));
    if (SDL_RenderReadPixels(renderer, nullptr, SDL_PIXELFORMAT_RGB24, rgb.data(),
                             static_cast<int>(row_bytes)) != 0) return false;
    std::vector<std::uint8_t> raw;
    raw.reserve((row_bytes + 1) * static_cast<std::size_t>(height));
    for (int y = 0; y < height; ++y) {
        raw.push_back(0);
        const auto begin = rgb.begin() + static_cast<std::ptrdiff_t>(static_cast<std::size_t>(y) * row_bytes);
        raw.insert(raw.end(), begin, begin + static_cast<std::ptrdiff_t>(row_bytes));
    }
    std::vector<std::uint8_t> png{137, 80, 78, 71, 13, 10, 26, 10};
    auto be32 = [](std::vector<std::uint8_t>& out, std::uint32_t value) {
        out.push_back(static_cast<std::uint8_t>(value >> 24));
        out.push_back(static_cast<std::uint8_t>(value >> 16));
        out.push_back(static_cast<std::uint8_t>(value >> 8));
        out.push_back(static_cast<std::uint8_t>(value));
    };
    auto chunk = [&](const char type[4], const std::vector<std::uint8_t>& payload) {
        be32(png, static_cast<std::uint32_t>(payload.size()));
        const std::size_t crc_begin = png.size();
        png.insert(png.end(), type, type + 4);
        png.insert(png.end(), payload.begin(), payload.end());
        std::uint32_t crc = 0xffffffffu;
        for (std::size_t i = crc_begin; i < png.size(); ++i) {
            crc ^= png[i];
            for (int bit = 0; bit < 8; ++bit) crc = (crc >> 1) ^ (0xedb88320u & (0u - (crc & 1u)));
        }
        be32(png, ~crc);
    };
    std::vector<std::uint8_t> header;
    be32(header, static_cast<std::uint32_t>(width));
    be32(header, static_cast<std::uint32_t>(height));
    header.insert(header.end(), {8, 2, 0, 0, 0});
    chunk("IHDR", header);
    std::vector<std::uint8_t> zlib{0x78, 0x01};
    for (std::size_t offset = 0; offset < raw.size();) {
        const std::size_t count = std::min<std::size_t>(65535, raw.size() - offset);
        const auto length = static_cast<std::uint16_t>(count);
        const auto inverse = static_cast<std::uint16_t>(~length);
        zlib.push_back(offset + count == raw.size() ? 1 : 0);
        zlib.push_back(static_cast<std::uint8_t>(length));
        zlib.push_back(static_cast<std::uint8_t>(length >> 8));
        zlib.push_back(static_cast<std::uint8_t>(inverse));
        zlib.push_back(static_cast<std::uint8_t>(inverse >> 8));
        zlib.insert(zlib.end(), raw.begin() + static_cast<std::ptrdiff_t>(offset),
                    raw.begin() + static_cast<std::ptrdiff_t>(offset + count));
        offset += count;
    }
    std::uint32_t a = 1, b = 0;
    for (const std::uint8_t byte : raw) { a = (a + byte) % 65521; b = (b + a) % 65521; }
    be32(zlib, (b << 16) | a);
    chunk("IDAT", zlib);
    chunk("IEND", {});
    std::error_code error;
    std::filesystem::create_directories(path.parent_path(), error);
    std::ofstream out(path, std::ios::binary);
    if (!out) return false;
    out.write(reinterpret_cast<const char*>(png.data()), static_cast<std::streamsize>(png.size()));
    return static_cast<bool>(out);
}
